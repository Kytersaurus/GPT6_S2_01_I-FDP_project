                vehicle_tilt                  <= 0;
                spin                          <= 0;
                spin_frac                     <= 0;
                last_tip                      <= 0;
                held_target                   <= 0;
                held_count                    <= 0;
                last_turn_valid               <= 0;
                equilibrium_count             <= 0;
                last_turn_from_tilt           <= 0;
                unstable_settled_dir          <= 0;
                stationary_anchor_x_px        <= $signed(spawn_x[19:8]);
                vehicle_x                     <= spawn_x;
                vehicle_y                     <= spawn_y;
                display_x                     <= spawn_x;
                display_y                     <= spawn_y;
                display_vx                    <= 0;
                display_vy                    <= 0;
