    assign vertical_sum = $signed({velocity_y[15], velocity_y}) +
                          17'sd32 - $signed({total_lift[15], total_lift});
    wire signed [16:0] net_gravity = 17'sd32 - $signed({total_lift[15], total_lift});
    wire [7:0] slope_magnitude = (sampled_slope < 0) ? -sampled_slope : sampled_slope;

    // Horizontal gravity on y=s*x is g*s/(1+s*s). A small constant
    // table avoids a second divider and preserves symmetric left/right forces.
    // Coefficients are round(256*(q/16)/(1+(q/16)^2)), q in [0,16].
    function [7:0] slope_factor;
        input [7:0] q;
        begin
            case (q)
                0:  slope_factor = 0;
                1:  slope_factor = 16;
                2:  slope_factor = 32;
                3:  slope_factor = 46;
                4:  slope_factor = 60;
                5:  slope_factor = 73;
                6:  slope_factor = 84;
                7:  slope_factor = 94;
                8:  slope_factor = 102;
                9:  slope_factor = 109;
                10: slope_factor = 115;
                11: slope_factor = 120;
                12: slope_factor = 123;
                13: slope_factor = 125;
                14: slope_factor = 127;
                15: slope_factor = 128;
                16: slope_factor = 128;
                default: slope_factor = 0;
            endcase
        end
    endfunction

    // Share two existing multipliers across separate FSM stages. Writing each
    // product twice lets synthesis create extra DSPs even though times differ.
    wire signed [16:0] slope_down_accel = (phase == VERTICAL_SLOPE) ? step_down_accel : net_gravity;
    wire [23:0] slope_product = slope_down_accel * slope_factor(slope_magnitude);
    wire signed [15:0] mass_multiply_term = (phase == SLOPE_FORCE) ?
                                            $signed(step_slope_product[23:8]) : step_vx;
    // Preserve this shared output; otherwise Vivado copies the multiplier
    // into the horizontal momentum multiply-accumulate stage.
    (* keep = "true" *) wire signed [24:0] mass_product = $signed({1'b0, step_mass}) * mass_multiply_term;

    reg divider_start;
    reg signed [15:0] divider_input;
