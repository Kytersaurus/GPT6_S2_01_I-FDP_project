// One rigid body. Coordinates are quarter pixels relative to grid centre.
// A single serial multiplier and divider are reused across all nine cells.
module vehicle_moments #(
    parameter integer ROCKET_FORCE_SHIFT   = 9,
    parameter integer FAN_LIFT_FORCE_SHIFT = 8
) (
    input wire clk,
    input wire reset,
    input wire start,
    input wire [26:0] build_grid,
    input wire [8:0] build_frames,
    input wire [8:0] intact_mask,
    input wire [8:0] frame_intact_mask,
    input wire [8:0] facing_left,
    input wire [8:0] rocket_vertical_mask,
    input tri0 [8:0] fan_lift_mask,
    input tri1 [8:0] fan_active_mask,
    input wire fan_on,
    input wire rocket_on,
    input wire grounded,
    // Only burning rockets push. Unconnected, every rocket follows rocket_on.
    input tri1 [8:0] rocket_burn_mask,
    input wire signed [`LP_TILT_BITS-1:0] tilt,
    // Accepted terrain contacts in world x, relative to the grid centre (Q2).
    // Omitted ports retain the inferred-wheel fallback for legacy callers.
    input tri0 contact_span_valid,
    input tri0 single_wheel_only,
    input tri0 signed [9:0] contact_left_q2,
    input tri0 signed [9:0] contact_right_q2,
    input tri0 signed [9:0] contact_y_q2,
    input tri0 contact_endpoint_y_valid,
