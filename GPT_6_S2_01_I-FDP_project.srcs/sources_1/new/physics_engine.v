// Vehicle movement and velocity.
`timescale 1ns / 1ps
`include "game_defs.vh"

// Staged forces, serial mass divider, slope gravity and friction.
// ENGINE_FORCE is the ground thrust per engine. The arithmetic benches keep the
// original 96; the game sets its tuned value in My_Top_Module.
module physics_engine #(
    parameter integer ENGINE_FORCE         = 96,
    parameter integer ROCKET_FORCE_SHIFT   = 9,
    parameter integer FAN_LIFT_FORCE_SHIFT = 8
) (
    input wire clk,
    input wire reset,
    input wire [2:0] game_state,
    input wire run_init,
    output reg init_ready,
    input wire signed [`LP_COORD_BITS-1:0] spawn_x,
    input wire signed [`LP_COORD_BITS-1:0] spawn_y,
    input wire step_start,
    input wire update_release,
    input wire [3:0] wheel_count,
    input wire [3:0] engine_count,
    input wire [3:0] balloon_count,
    // Wheels under (down) and on top of (up) the body. Left unconnected, both
    // are zero and the total wheel_count is used whichever way up the body is.
    input tri0 [3:0] wheels_down,
    input tri0 [3:0] wheels_up,
    input wire [7:0] mass_units,
    input wire engine_enabled,
    input wire engine_reverse,
    // Signed intact part counts: right-facing minus left-facing. Unconnected
    // ports preserve legacy benches with no airborne propulsion.
    input tri0 signed [4:0] fan_balance,
    input tri0 signed [4:0] rocket_balance,
    // Future downward-blowing fans: upward WORLD force, independent of facing.
    // Count only surviving lift fans here; exclude them from fan_balance.
    // The matching per-cell mask supplies their lever arms to the moments unit.
    input tri0 [3:0] live_lift_fan_count,
    input tri0 [8:0] fan_lift_mask,
    input tri1 [8:0] fan_active_mask,
    // Future placement logic supplies body-vertical rockets: down minus up.
    input tri0 signed [4:0] rocket_vertical_balance,
    input tri0 [3:0] rocket_count,
    input tri0 fan_enabled,
    input tri0 rocket_req,
    input tri0 tutorial_mode,
    // Rockets burn independently. rocket_fire_mask names the cell(s) rocket_req
    // lights and rocket_present_mask the rockets on the cart. Left unconnected,
    // both are all ones: one request lights every rocket together.
    input tri1 [8:0] rocket_fire_mask,
    input tri1 [8:0] rocket_present_mask,
    output wire rocket_ready,
    output wire rocket_active,
    output wire [8:0] rocket_burn_mask,
    output reg [8:0] rocket_spent_mask,
    // Read-only geometry for force application and the mass centre. Disabled
    // by default for legacy arithmetic benches; the game enables it explicitly.
    input tri0 moments_enabled,
    input tri0 [26:0] build_grid,
    input tri0 [8:0] build_frames,
    input tri0 [8:0] intact_mask,
    input tri0 [8:0] frame_intact_mask,
    input tri0 [8:0] build_facing_left,
    input tri0 [8:0] rocket_vertical_mask,
    // One-shot outward impulse generated by a TNT explosion. These ports
    // default low for legacy physics benches that do not use TNT.
    input tri0 tnt_knockback_valid,
    input tri0 signed [15:0] tnt_knockback_x,
    input tri0 signed [15:0] tnt_knockback_y,
    output wire move_valid,
    input wire move_ready,
    output reg signed [`LP_COORD_BITS-1:0] previous_x,
    output reg signed [`LP_COORD_BITS-1:0] previous_y,
    output reg signed [`LP_COORD_BITS-1:0] proposed_x,
    output reg signed [`LP_COORD_BITS-1:0] proposed_y,
    output reg signed [15:0] proposed_vx,
    output reg signed [15:0] proposed_vy,
    output wire signed [13:0] proposed_pivot_dx_q8,
    output wire signed [13:0] proposed_pivot_dy_q8,
    input wire response_valid,
    output wire response_ready,
    input wire signed [`LP_COORD_BITS-1:0] corrected_x,
    input wire signed [`LP_COORD_BITS-1:0] corrected_y,
    input wire signed [15:0] corrected_vx,
    input wire signed [15:0] corrected_vy,
    input wire grounded,
    input wire signed [7:0] ground_slope,
    input tri1 ground_slope_valid,
    input tri0 support_span_valid,
    input tri0 [3:0] support_wheel_count,
    input tri0 signed [9:0] support_left_q2,
    input tri0 signed [9:0] support_right_q2,
    input tri0 signed [9:0] support_y_q2,
    input tri0 support_endpoint_y_valid,
    input tri0 signed [9:0] support_left_y_q2,
    input tri0 signed [9:0] support_right_y_q2,
    input wire signed [`LP_TILT_BITS-1:0] corrected_tilt,
    // Collision's report that the body is balanced past a supporting edge.
    input tri0 signed [1:0] tip_dir,
    input tri0 support_unstable,
    output reg signed [`LP_TILT_BITS-1:0] previous_tilt,
    output reg signed [`LP_TILT_BITS-1:0] proposed_tilt,
    output reg signed [`LP_TILT_BITS-1:0] vehicle_tilt,
    output reg movement_committed,
    output reg signed [`LP_COORD_BITS-1:0] vehicle_x,
    output reg signed [`LP_COORD_BITS-1:0] vehicle_y,
    // Drawing position: the horizontal pose is an alpha-beta filtered copy of
    // the committed physics pose. Grounded y is committed exactly so the OLED
    // sprite stays on the terrain; airborne y remains filtered. Collision and
    // outcomes continue to use the unfiltered vehicle_x/vehicle_y values.
    output reg signed [`LP_COORD_BITS-1:0] display_x,
    output reg signed [`LP_COORD_BITS-1:0] display_y
);
    `include "rotation_geometry.vh"

    localparam IDLE              = 0;
    localparam MOMENTUM          = 1;
    localparam FREE_MOMENTUM     = 2;
    localparam FRICTION          = 3;
    localparam TOTAL_FORCE       = 4;
    localparam START_DIV         = 5;
    localparam WAIT_DIV          = 6;
    localparam CLAMP_VELOCITY    = 7;
    localparam POSITION          = 8;
    localparam MAKE_REQUEST      = 9;
    localparam SEND              = 10;
    localparam WAIT_RESPONSE     = 11;
    localparam WAIT_WORLD        = 12;
    localparam CALC_FORCE        = 13;
    localparam SLOPE_FORCE       = 14;
    localparam APPLY_SLOPE       = 15;
    localparam AIR_FORCE         = 16;
    localparam VERTICAL_START    = 17;
    localparam VERTICAL_WAIT     = 18;
    localparam VERTICAL_CLAMP    = 19;
    localparam MOMENT_WAIT       = 20;
    localparam ROTATE_FORCE      = 21;
    localparam PIVOT_START       = 22;
    localparam PIVOT_WAIT        = 23;
    localparam APPLY_PIVOT       = 24;
    localparam ROCKET_HORIZONTAL = 25;
    localparam ROCKET_VERTICAL   = 26;
    localparam ROCKET_DONE       = 27;
    localparam VERTICAL_SLOPE    = 28;
    localparam FAN_HORIZONTAL    = 29;
    localparam FAN_LIFT          = 30;

    localparam signed [15:0] wheel_drag = 16'sd6;
    // A wheeled body resting on its side without wheels scrapes instead of rolling.
    // Bodies with no wheel sides reported (no wheels, or legacy inputs) keep the
    // original zero-wheel behaviour.
    localparam signed [15:0] scrape_drag = 16'sd256;
    // Spin is in 1/16 tilt steps per update: 16 turns 11.25 degrees each update.
    // Tipping over an edge adds TIP_ACCEL per update, up to MAX_SPIN.
    localparam signed [5:0] TIP_ACCEL = 6'sd3;
    localparam signed [5:0] MAX_SPIN  = 6'sd16;
    localparam signed [15:0] engine_force = ENGINE_FORCE;
    // TNT is allowed a short launch burst above the ordinary drive limit.
    // The limit returns to the normal value after the burst expires.
    localparam signed [15:0] TNT_MAX_VX = 16'sd768;
    localparam signed [15:0] TNT_MAX_VY = 16'sd768;
    localparam [4:0] TNT_BLAST_STEPS = 5'd16; // Physics updates (about 1/4 s at 60 Hz)
    // Two available balloons must overcome gravity (32); one slows a fall.
    localparam signed [15:0] lift_per_balloon = 16'sd24;

    // Power-of-two per-part forces use wiring shifts, not multipliers.
    localparam FAN_FORCE_SHIFT = 6; // Fan force 64; rocket force is a power-of-two parameter.
    localparam [6:0] ROCKET_TICKS = 7'd90; // 1.5 s at the default 60 Hz
    // One short TNT-clearing hop. The tutorial cart's balloon leaves only 8 of 32 gravity,
    // so even 5 ticks of thrust lift it about 15 px, over the 8 px crate and back down.
    localparam [6:0] TUTORIAL_ROCKET_TICKS = 7'd5;

    reg [4:0] phase;
    reg signed [15:0] velocity_x;
    reg signed [15:0] velocity_y;
    reg [4:0] tnt_blast_steps;
    wire tnt_blast_active = (tnt_blast_steps != 0);
    wire signed [15:0] active_vx_limit = tnt_blast_active ? TNT_MAX_VX : 16'sd256;
    wire signed [15:0] active_vy_limit = tnt_blast_active ? TNT_MAX_VY : 16'sd512;
    wire signed [16:0] active_vx_limit_ext = {active_vx_limit[15], active_vx_limit};
    wire signed [17:0] active_vy_limit_ext = {{2{active_vy_limit[15]}}, active_vy_limit};
    wire signed [16:0] tnt_velocity_sum_x =
        $signed({velocity_x[15], velocity_x}) + $signed({tnt_knockback_x[15], tnt_knockback_x});
    wire signed [16:0] tnt_velocity_sum_y =
        $signed({velocity_y[15], velocity_y}) + $signed({tnt_knockback_y[15], tnt_knockback_y});
    wire signed [15:0] tnt_velocity_after_x =
        (tnt_velocity_sum_x > $signed({1'b0, TNT_MAX_VX})) ? TNT_MAX_VX :
        (tnt_velocity_sum_x < -$signed({1'b0, TNT_MAX_VX})) ? -TNT_MAX_VX : tnt_velocity_sum_x[15:0];
    wire signed [15:0] tnt_velocity_after_y =
        (tnt_velocity_sum_y > $signed({1'b0, TNT_MAX_VY})) ? TNT_MAX_VY :
        (tnt_velocity_sum_y < -$signed({1'b0, TNT_MAX_VY})) ? -TNT_MAX_VY : tnt_velocity_sum_y[15:0];
    reg was_grounded;
    // Two burn timers, because a level allows at most two rockets (Cave Flight).
    // Each remembers which cell(s) it is burning.
    reg [6:0] rocket_fuel;
    reg [6:0] second_rocket_fuel;
    reg [8:0] first_burn_cells;
    reg [8:0] second_burn_cells;
    wire rocket_spent = |rocket_spent_mask;
    assign rocket_burn_mask = ((rocket_fuel != 0) ? first_burn_cells : 9'd0) |
                              ((second_rocket_fuel != 0) ? second_burn_cells : 9'd0);
    reg signed [4:0] sampled_fans;
    reg signed [4:0] sampled_rockets;
    reg signed [4:0] sampled_vertical_rockets;
    reg [3:0] sampled_lift_fans;
    reg signed [15:0] step_vertical_force;
    reg signed [9:0] sampled_rocket_cos;
    reg signed [9:0] sampled_rocket_sin;
    reg [4:0] rocket_terms;
    reg signed [15:0] rocket_force_x;
    reg signed [15:0] rocket_force_y;
    wire signed [15:0] rocket_unit_x = $signed({{6{sampled_rocket_cos[9]}}, sampled_rocket_cos}) <<< (ROCKET_FORCE_SHIFT - 8);
    wire signed [15:0] rocket_unit_y = $signed({{6{sampled_rocket_sin[9]}}, sampled_rocket_sin}) <<< (ROCKET_FORCE_SHIFT - 8);
    // One fan's force along the tilted body axes. cos/sin are Q8 (256 = 1.0), so
    // shift up by the force's power of two and drop the low 8 bits. Wiring only.
    wire signed [23:0] fan_cos_wide = $signed({{14{sampled_rocket_cos[9]}}, sampled_rocket_cos});
    wire signed [23:0] fan_sin_wide = $signed({{14{sampled_rocket_sin[9]}}, sampled_rocket_sin});
    wire signed [23:0] fan_side_x_wide = fan_cos_wide <<< FAN_FORCE_SHIFT;
    wire signed [23:0] fan_side_y_wide = fan_sin_wide <<< FAN_FORCE_SHIFT;
    wire signed [23:0] fan_lift_x_wide = fan_cos_wide <<< FAN_LIFT_FORCE_SHIFT;
    wire signed [23:0] fan_lift_y_wide = fan_sin_wide <<< FAN_LIFT_FORCE_SHIFT;
    wire signed [15:0] fan_side_unit_x = fan_side_x_wide[23:8];
    wire signed [15:0] fan_side_unit_y = fan_side_y_wide[23:8];
    wire signed [15:0] fan_lift_unit_x = fan_lift_x_wide[23:8];
    wire signed [15:0] fan_lift_unit_y = fan_lift_y_wide[23:8];
    reg signed [15:0] remainder_y;
    reg signed [15:0] pending_remainder_y;
    reg signed [16:0] step_vertical_base;
    reg signed [17:0] step_vy_sum;
    reg signed [16:0] step_down_accel;
    reg signed [15:0] step_air_force;
    wire menu_paused = (game_state == `LP_SETTINGS) || (game_state == `LP_GUIDE);
    reg step_moments_enabled;
    reg wheel_force_valid;
    reg signed [15:0] step_vy;
    reg step_support_unstable;
    reg last_support_span_valid;
    reg last_ground_slope_valid;
    reg [3:0] last_support_wheel_count;
    reg signed [9:0] last_support_left_q2;
    reg signed [9:0] last_support_right_q2;
    reg signed [9:0] last_support_y_q2;
    reg last_support_endpoint_y_valid;
    reg signed [9:0] last_support_left_y_q2;
    reg signed [9:0] last_support_right_y_q2;
    reg signed [7:0] last_ground_slope;
    reg signed [7:0] sampled_slope;
    reg signed [1:0] last_tip;
    reg signed [13:0] angular_velocity_q8;
    reg signed [12:0] moment_angle_remainder;
    reg signed [17:0] step_angular_sum;
    reg signed [13:0] step_pivot_x;
    reg signed [13:0] step_pivot_y;
    assign proposed_pivot_dx_q8 = step_moments_enabled ? step_pivot_x : 14'sd0;
    assign proposed_pivot_dy_q8 = step_moments_enabled ? step_pivot_y : 14'sd0;
    wire moment_valid;
    wire pivot_valid;
    wire signed [15:0] moment_accel;
    wire signed [15:0] gravity_tilt_q8;
    wire contact_support_unstable;
    wire [15:0] support_negative_q8;
    wire [15:0] support_positive_q8;
    reg signed [15:0] supported_moment_accel;
    wire signed [13:0] pivot_dx;
    wire signed [13:0] pivot_dy;
    wire [3:0] wheel_side = tilt_flipped(vehicle_tilt) ? wheels_up : wheels_down;
    // The builder's wheel and frame counts are long combinational sums over the damage
    // masks, and they feed the angular-velocity adder. They change only when a part
    // breaks, far less often than a physics step, so one register here costs nothing
    // in behaviour and takes those sums out of the 100 MHz path.
    reg [3:0] legacy_contact_wheels;
    reg has_intact_frames;

    always @ (posedge clk) begin
        legacy_contact_wheels <= ((wheels_down | wheels_up) == 0) ? wheel_count : wheel_side;
        has_intact_frames     <= (frame_intact_mask & build_frames) != 9'd0;
    end

    wire [3:0] contact_wheels = last_support_span_valid ? last_support_wheel_count : legacy_contact_wheels;
    reg signed [`LP_TILT_BITS-1:0] slope_tilt;
    wire signed [`LP_TILT_BITS-1:0] desired_tilt = tilt_flipped(vehicle_tilt) ? (slope_tilt + 5'b10000) : slope_tilt;
    // Shortest way round: the 5-bit difference wraps to -16..15.
    wire signed [`LP_TILT_BITS-1:0] settle_error = desired_tilt - vehicle_tilt;
    wire signed [10:0] support_span_width_q2 = $signed(last_support_right_q2) - $signed(last_support_left_q2);
    wire single_wheel_grounded = was_grounded && last_support_span_valid &&
                                 (legacy_contact_wheels == 4'd1) && has_intact_frames;
    wire single_wheel_scraping = single_wheel_grounded &&
                                 ((last_support_wheel_count == 4'd0) ||
                                  ((last_support_wheel_count == 4'd1) && (support_span_width_q2 > 11'sd52)));
    wire frame_tip_only = single_wheel_grounded && (last_support_wheel_count == 4'd0) &&
                          (support_span_width_q2 <= 11'sd52) && (settle_error[2:0] != 3'd0);
    wire single_wheel_only = (single_wheel_grounded && (last_support_wheel_count == 4'd1) &&
                              (support_span_width_q2 <= 11'sd52)) || frame_tip_only;
    wire effective_support_unstable = contact_support_unstable;
    wire signed [13:0] clamped_angular_velocity =
        (step_angular_sum > 18'sd4096) ? 14'sd4096 :
        (step_angular_sum < -18'sd4096) ? -14'sd4096 : step_angular_sum[13:0];
    wire pivot_about_contact = was_grounded && (step_vy >= 0) && last_support_span_valid &&
                               (step_support_unstable || (supported_moment_accel != 0));
    reg step_pivot_about_contact;
    wire signed [`LP_TILT_BITS-1:0] pivot_turn = proposed_tilt - vehicle_tilt;
    wire signed [1:0] pivot_direction = (pivot_turn > 0) ? 2'sd1 : (pivot_turn < 0) ? -2'sd1 : last_tip;
    // Take drag from the magnitude, then restore its sign. Arithmetic shifts
    // of negative speeds would otherwise damp the two directions differently.
    wire [13:0] angular_speed = (angular_velocity_q8 < 0) ? -angular_velocity_q8 : angular_velocity_q8;
    wire signed [13:0] air_drag_q8 = $signed({1'b0, angular_speed[13:3]});
    wire signed [13:0] ground_drag_q8 = $signed({1'b0, angular_speed[13:2]});
    wire signed [13:0] ground_angular_velocity =
        (angular_velocity_q8 < 0) ? (angular_velocity_q8 + ground_drag_q8) : (angular_velocity_q8 - ground_drag_q8);
    // With no torque, snap the last sub-pixel motion to rest.
    wire signed [13:0] air_angular_velocity =
        ((moment_accel == 0) && (!effective_support_unstable || (gravity_tilt_q8 == 0) || (step_vy < 0)) && (angular_speed < 14'd64)) ? 14'sd0 :
        ((angular_velocity_q8 < 0) ? (angular_velocity_q8 + air_drag_q8) : (angular_velocity_q8 - air_drag_q8));
    // During the descending part of a jump, gravity and rotational inertia should
    // bring a cart gently toward a level landing pose. Use a small proportional
    // righting term rather than a fixed torque: a one-step tilt is corrected very
    // gently, while a large tilt receives more help. This uses a shift only, so
    // it does not infer a multiplier or consume BRAM.
    wire signed [17:0] air_tilt_q8 = {{13{vehicle_tilt[4]}}, vehicle_tilt};
    wire air_leveling_active = tutorial_mode && !was_grounded && (step_vy > 16'sd64) &&
                               !fan_enabled && !rocket_active && (vehicle_tilt != 0);
    wire signed [17:0] air_level_accel = air_leveling_active ? -(air_tilt_q8 <<< 6) : 18'sd0;
    wire air_leveling_snap = air_leveling_active &&
                             ((vehicle_tilt == 5'sd1) || (vehicle_tilt == -5'sd1)) &&
                             (angular_speed < 14'd512);
    wire signed [15:0] force_angle_sum = $signed(moment_angle_remainder) + $signed(clamped_angular_velocity);

    vehicle_moments #(
        .ROCKET_FORCE_SHIFT(ROCKET_FORCE_SHIFT),
        .FAN_LIFT_FORCE_SHIFT(FAN_LIFT_FORCE_SHIFT)
    ) u_moments (
        .clk(clk),
        .reset(reset || run_init || (game_state != `LP_RUN)),
        .start((phase == IDLE) && step_start && moments_enabled && (game_state == `LP_RUN) && !run_init),
        .build_grid(build_grid),
        .build_frames(build_frames),
        .intact_mask(intact_mask),
        .frame_intact_mask(frame_intact_mask),
        .facing_left(build_facing_left),
        .rocket_vertical_mask(rocket_vertical_mask),
        .fan_lift_mask(fan_lift_mask),
        .fan_active_mask(fan_active_mask),
        .fan_on(fan_enabled),
        .rocket_on(rocket_active),
        .rocket_burn_mask(rocket_burn_mask),
        .grounded(was_grounded),
        .tilt(vehicle_tilt),
        .wheel_force_valid(wheel_force_valid),
        .contact_span_valid(last_support_span_valid),
        .single_wheel_only(single_wheel_only),
        .contact_left_q2(last_support_left_q2),
        .contact_right_q2(last_support_right_q2),
        .contact_y_q2(last_support_y_q2),
        .pivot_about_contact(step_pivot_about_contact),
        .pivot_direction(pivot_direction),
        .contact_endpoint_y_valid(last_support_endpoint_y_valid),
        .contact_left_y_q2(last_support_left_y_q2),
        .contact_right_y_q2(last_support_right_y_q2),
        .ground_slope(last_ground_slope),
        .ground_slope_valid(last_ground_slope_valid),
        .grounded_support_unstable(contact_support_unstable),
        .wheel_force(16'sd0),
        .result_valid(moment_valid),
        .result_ready(phase == MOMENT_WAIT),
        .angular_accel_q8(moment_accel),
        .support_negative_q8(support_negative_q8),
        .support_positive_q8(support_positive_q8),
        .com_x_q2(),
        .com_y_q2(),
        .body_mass(),
        .torque_q10(),
        .gravity_tilt_q8(gravity_tilt_q8),
        .pivot_start(phase == PIVOT_START),
        .next_tilt(proposed_tilt),
        .pivot_valid(pivot_valid),
        .pivot_ready(phase == PIVOT_WAIT),
        .pivot_dx(pivot_dx),
        .pivot_dy(pivot_dy)
    );

    // A rocket can still fire if it is on the cart and has not been used this run.
    wire [8:0] unfired_rockets = rocket_present_mask & ~rocket_spent_mask;
    wire [8:0] rockets_to_light = rocket_fire_mask & unfired_rockets;
    wire [6:0] full_rocket_burn = tutorial_mode ? TUTORIAL_ROCKET_TICKS : ROCKET_TICKS;
    wire rocket_burn_step = (game_state == `LP_RUN) && (phase == IDLE) && step_start;
    assign rocket_ready = (game_state == `LP_RUN) && !run_init &&
                          (|unfired_rockets) && (rocket_count != 0);
    assign rocket_active = (game_state == `LP_RUN) && !run_init &&
                           ((rocket_fuel != 0) || (second_rocket_fuel != 0)) && (rocket_count != 0);

    // Requests are captured even between physics steps. Each rocket is a one-shot
    // restored only by reset/retry, and only accepted updates consume fuel.
    always @ (posedge clk) begin
        if (reset || run_init || (game_state != `LP_RUN && !menu_paused)) begin
            rocket_fuel        <= 0;
            second_rocket_fuel <= 0;
            first_burn_cells   <= 0;
            second_burn_cells  <= 0;
            rocket_spent_mask  <= 0;
        end else begin
            if (rocket_burn_step && rocket_fuel != 0) begin
                rocket_fuel <= rocket_fuel - 1'b1;
            end
            if (rocket_burn_step && second_rocket_fuel != 0) begin
                second_rocket_fuel <= second_rocket_fuel - 1'b1;
            end
            if (rocket_req && rocket_ready && rockets_to_light != 0) begin
                rocket_spent_mask <= rocket_spent_mask | rockets_to_light;
                if (rocket_fuel == 0) begin
                    rocket_fuel      <= full_rocket_burn;
                    first_burn_cells <= rockets_to_light;
                end else begin
                    second_rocket_fuel <= full_rocket_burn;
                    second_burn_cells  <= rockets_to_light;
                end
            end
        end
    end

    // Accepted terrain gradient in Q4.4 dy/dx; positive descends to the right.
    // An upside-down body settles onto the slope with its top row down.
    // Terrain contact is committed before WAIT_WORLD. Cache the slope from the
    // accepted collision response itself; using last_ground_slope here would
    // add an extra physics update before the body starts rotating.
    always @ (posedge clk) begin
        if (reset || run_init) begin
            slope_tilt <= 0;
        end else if (game_state == `LP_RUN && response_valid && response_ready && grounded &&
                     ground_slope_valid && ground_slope >= -8'sd16 && ground_slope <= 8'sd16) begin
            slope_tilt <= slope_to_tilt(ground_slope);
        end else if (game_state == `LP_RUN && response_valid && response_ready && !grounded) begin
            slope_tilt <= 0;
        end
    end

    // Keep the target registers for compatibility with the existing moments
    // state machine, but do not wait for three identical slope samples. The
    // accepted collision slope is already filtered by the terrain probe, so a
    // supported vehicle can begin turning on the very next physics update.
