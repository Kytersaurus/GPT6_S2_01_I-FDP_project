            step_down_accel               <= 0;
            sampled_fans                  <= 0;
            sampled_rockets               <= 0;
            step_air_force                <= 0;
            last_ground_slope             <= 0;
            sampled_slope                 <= 0;
            last_support_unstable         <= 0;
            step_support_unstable         <= 0;
            last_ground_slope_valid       <= 0;
            last_support_span_valid       <= 0;
            last_support_wheel_count      <= 0;
            last_support_left_q2          <= 0;
            last_support_right_q2         <= 0;
            last_support_y_q2             <= 0;
            last_support_endpoint_y_valid <= 0;
            last_support_left_y_q2        <= 0;
            last_support_right_y_q2       <= 0;
