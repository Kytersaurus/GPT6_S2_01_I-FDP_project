        .clk(clk),
        .reset(divider_reset),
        .start(divider_start),
        .dividend(divider_input),
        .divisor(step_mass),
        .busy(divider_busy),
        .done(divider_done),
        .divide_by_zero(divider_zero),
        .quotient(divider_quotient),
        .remainder(divider_remainder)
    );

