                    end
                    CALC_FORCE: begin
                        // Part counting ends at the sampled registers above. Force
                        // multiplication/addition then has its own 100 MHz clock.
                        // Fan and rocket forces are summed serially by the phases below.
                        step_vertical_force <= 0;
                        rocket_force_x      <= 0;
                        rocket_force_y      <= 0;
                        rocket_terms        <= (sampled_fans < 0) ? -sampled_fans : sampled_fans;
                        step_vertical_base  <= vertical_sum;
                        step_air_force      <= 0;
                        step_thrust         <= 0;
                        // With wheel sides reported, only wheels touching the ground drive.
                        if (sampled_engine_enabled && sampled_engines != 0 &&
                            (sampled_wheels != 0 || (!sampled_sided && !step_moments_enabled)) && was_grounded) begin
                            if (sampled_scraping) begin
                                step_thrust <= sampled_engine_reverse ? -(engine_magnitude >>> 2) : (engine_magnitude >>> 2);
                            end else begin
                                step_thrust <= sampled_engine_reverse ? -engine_magnitude : engine_magnitude;
                            end
                        end
                        step_friction_limit <= was_grounded ?
                            (bowl_settled ? 16'd256 : (wheel_resistance + (unpowered_uphill ? 16'd128 : 16'd0))) : 16'd0;
                        if (vertical_sum > $signed({1'b0, active_vy_limit})) begin
                            step_vy <= active_vy_limit;
                        end else if (vertical_sum < -$signed({1'b0, active_vy_limit})) begin
                            step_vy <= -active_vy_limit;
                        end else begin
                            step_vy <= vertical_sum[15:0];
                        end
                        // Balloon lift reduces weight on the ramp.
                        if (was_grounded && net_gravity > 0 && !bowl_settled) begin
                            step_slope_product <= slope_product;
                        end else begin
                            step_slope_product <= 0;
                        end
                        if (sampled_fans != 0 || sampled_lift_fans != 0 ||
                            sampled_rockets != 0 || sampled_vertical_rockets != 0) begin
                            phase <= FAN_HORIZONTAL;
                        end else if (remainder_y != 0) begin
                            phase <= VERTICAL_START;
                        end else begin
                            phase <= SLOPE_FORCE;
                        end
                    end
                    FAN_HORIZONTAL: begin
                        // A fan's force tilts with the body. A negative balance means
                        // the fans push toward +X along the body's own axis.
                        if (rocket_terms == 0) begin
                            rocket_terms <= sampled_lift_fans;
                            phase        <= FAN_LIFT;
                        end else begin
                            rocket_force_x <= rocket_force_x + ((sampled_fans < 0) ? fan_side_unit_x : -fan_side_unit_x);
                            rocket_force_y <= rocket_force_y + ((sampled_fans < 0) ? fan_side_unit_y : -fan_side_unit_y);
                            rocket_terms   <= rocket_terms - 1'b1;
                        end
                    end
                    FAN_LIFT: begin
                        // Downward fans push along the body's "up", so a tilted
                        // vehicle drifts sideways instead of hovering straight up.
                        if (rocket_terms == 0) begin
                            rocket_terms <= (sampled_rockets < 0) ? -sampled_rockets : sampled_rockets;
                            phase        <= ROCKET_HORIZONTAL;
                        end else begin
                            rocket_force_x <= rocket_force_x + fan_lift_unit_y;
                            rocket_force_y <= rocket_force_y - fan_lift_unit_x;
                            rocket_terms   <= rocket_terms - 1'b1;
                        end
                    end
                    ROCKET_HORIZONTAL: begin
                        // The thrust vector rotates with the attached rocket. Sum
                        // bounded per-rocket vectors serially instead of multiplying.
                        if (rocket_terms == 0) begin
                            rocket_terms <= (sampled_vertical_rockets < 0) ? -sampled_vertical_rockets : sampled_vertical_rockets;
                            phase        <= ROCKET_VERTICAL;
                        end else begin
                            rocket_force_x <= rocket_force_x + ((sampled_rockets < 0) ? -rocket_unit_x : rocket_unit_x);
                            rocket_force_y <= rocket_force_y + ((sampled_rockets < 0) ? -rocket_unit_y : rocket_unit_y);
                            rocket_terms   <= rocket_terms - 1'b1;
                        end
                    end
                    ROCKET_VERTICAL: begin
                        if (rocket_terms == 0) begin
                            phase <= ROCKET_DONE;
                        end else begin
                            rocket_force_x <= rocket_force_x + ((sampled_vertical_rockets < 0) ? rocket_unit_y : -rocket_unit_y);
                            rocket_force_y <= rocket_force_y + ((sampled_vertical_rockets < 0) ? -rocket_unit_x : rocket_unit_x);
                            rocket_terms   <= rocket_terms - 1'b1;
                        end
                    end
                    ROCKET_DONE: begin
                        step_air_force      <= rocket_force_x;
                        step_vertical_force <= rocket_force_y;
                        phase               <= VERTICAL_START;
                    end
                    SLOPE_FORCE: begin
                        // Convert acceleration to force before the existing mass
                        // division. Wheel resistance can balance it at rest.
                        // CoG imbalance changes angular support, never propulsion.
                        // Only a valid measured gradient projects gravity onto x.
                        if (sampled_slope < 0) begin
                            step_slope_force <= -$signed(mass_product[15:0]);
                        end else begin
                            step_slope_force <= mass_product[15:0];
                        end
                        phase <= APPLY_SLOPE;
                    end
                    APPLY_SLOPE: begin
                        step_thrust <= step_thrust + step_slope_force;
                        phase       <= AIR_FORCE;
                    end
                    AIR_FORCE: begin
                        step_thrust <= step_thrust + step_air_force;
                        phase       <= MOMENTUM;
                    end
                    MOMENTUM: begin
                        // An unsigned 8-bit mass needs a leading zero before it
                        // participates in signed multiplication.
                        step_momentum <= mass_product;
                        // Compare the captured mass here, after the builder's count
                        // calculation has ended at step_mass's register boundary.
                        if (step_mass == remainder_mass) begin
                            step_drive <= step_thrust + step_remainder;
                        end else begin
                            step_remainder <= 0;
                            step_drive     <= step_thrust;
                        end
                        phase <= FREE_MOMENTUM;
                    end
                    FREE_MOMENTUM: begin
                        step_free_momentum <= step_momentum +
                                              $signed({{9{step_drive[15]}}, step_drive});
                        phase <= FRICTION;
                    end
                    FRICTION: begin
                        // Include the saved fraction in the stopping calculation.
                        // Friction can stop a body, but cannot make it reverse.
                        if (step_free_momentum > $signed({1'b0, step_friction_limit})) begin
                            step_friction <= -$signed(step_friction_limit);
                        end else if (step_free_momentum < -$signed({1'b0, step_friction_limit})) begin
                            step_friction <= $signed(step_friction_limit);
                        end else begin
                            step_friction <= -$signed(step_free_momentum[15:0]);
                        end
                        phase <= TOTAL_FORCE;
                    end
                    TOTAL_FORCE: begin
                        wheel_force_valid <= 1;
                        total_force       <= step_thrust + step_friction;
                        phase             <= START_DIV;
                    end
                    START_DIV: begin
                        if (!divider_busy) begin
                            // All horizontal acceleration comes from force / mass.
                            // Carry the remainder so small forces are not rounded away.
                            divider_input <= total_force + step_remainder;
                            divider_start <= 1;
                            phase         <= WAIT_DIV;
                        end
                    end
                    WAIT_DIV: begin
                        if (divider_done) begin
                            step_vx_sum         <= $signed({step_vx[15], step_vx}) +
                                                   $signed({divider_quotient[15], divider_quotient});
                            pending_remainder_x <= divider_zero ? 16'sd0 : divider_remainder;
                            phase               <= CLAMP_VELOCITY;
                        end
                    end
                    CLAMP_VELOCITY: begin
                        if (step_vx_sum > active_vx_limit_ext) begin
                            step_result_vx      <= active_vx_limit;
                            pending_remainder_x <= 0;
                        end else if (step_vx_sum < -active_vx_limit_ext) begin
                            step_result_vx      <= -active_vx_limit;
                            pending_remainder_x <= 0;
                        end else begin
                            step_result_vx <= step_vx_sum[15:0];
                            if ((step_vx_sum == 17'sd256 && pending_remainder_x > 0) ||
                                (step_vx_sum == -17'sd256 && pending_remainder_x < 0)) begin
                                pending_remainder_x <= 0;
                            end
                        end
                        phase <= MOMENT_WAIT;
                    end
                    VERTICAL_START: begin
                        // Time-share the horizontal serial divider: no second divider
                        // or multiplier is required for vertical fan/rocket thrust.
                        if (step_vertical_force == 0 && remainder_y == 0) begin
                            phase <= SLOPE_FORCE;
                        end else if (!divider_busy) begin
                            divider_input <= step_vertical_force +
                                             ((step_mass == remainder_mass) ? remainder_y : 16'sd0);
                            divider_start <= 1;
                            phase         <= VERTICAL_WAIT;
                        end
                    end
                    VERTICAL_WAIT: begin
                        if (divider_done) begin
                            step_vy_sum         <= $signed({step_vertical_base[16], step_vertical_base}) +
                                                   $signed({{2{divider_quotient[15]}}, divider_quotient});
                            pending_remainder_y <= divider_zero ? 16'sd0 : divider_remainder;
                            step_down_accel     <= net_gravity + $signed({divider_quotient[15], divider_quotient});
                            phase               <= VERTICAL_CLAMP;
                        end
                    end
                    VERTICAL_CLAMP: begin
                        if (step_vy_sum > active_vy_limit_ext) begin
                            step_vy             <= active_vy_limit;
                            pending_remainder_y <= 0;
                        end else if (step_vy_sum < -active_vy_limit_ext) begin
                            step_vy             <= -active_vy_limit;
                            pending_remainder_y <= 0;
                        end else begin
                            step_vy <= step_vy_sum[15:0];
                            if ((step_vy_sum == 18'sd512 && pending_remainder_y > 0) ||
                                (step_vy_sum == -18'sd512 && pending_remainder_y < 0)) begin
                                pending_remainder_y <= 0;
                            end
                        end
                        phase <= VERTICAL_SLOPE;
                    end
                    VERTICAL_SLOPE: begin
                        // Project the remaining downward acceleration after lift.
                        // Enough upward thrust detaches without a downhill push.
                        // Reuse the existing slope multiplier, after mass division.
                        if (was_grounded && step_vy >= 0 && step_down_accel > 0 && !bowl_settled) begin
                            step_slope_product <= slope_product;
                        end else begin
                            step_slope_product <= 0;
                        end
                        phase <= SLOPE_FORCE;
                    end
                    MOMENT_WAIT: begin
                        if (!step_moments_enabled) begin
                            phase <= POSITION;
                        end else if (moment_valid) begin
                            step_support_unstable <= effective_support_unstable;
                            if (was_grounded && step_vy >= 0 &&
                                !effective_support_unstable && last_ground_slope_valid) begin
                                if (desired_tilt != held_target) begin
                                    held_target <= desired_tilt;
                                    held_count  <= 1;
                                end else if (held_count != 2'd2) begin
                                    held_count <= held_count + 1'b1;
                                end
                            end else begin
                                held_count <= 0;
                            end
                            // Ground loses a quarter of spin; air loses an eighth.
                            // Active fan/rocket torque can still accelerate rotation.
                            step_angular_sum <=
                                ((was_grounded && step_vy >= 0 && !effective_support_unstable) ?
                                 $signed(ground_angular_velocity) :
                                 $signed(air_angular_velocity)) + $signed(supported_moment_accel) +
                                ((effective_support_unstable && step_vy >= 0) ? $signed(gravity_tilt_q8) : 18'sd0) +
                                $signed(air_level_accel) +
                                (was_grounded ?
                                 ((active_tip > 0) ? 18'sd256 : (active_tip < 0) ? -18'sd256 : 18'sd0) : 18'sd0);
                            phase <= ROTATE_FORCE;
                        end
                    end
                    ROTATE_FORCE: begin
                        step_pivot_about_contact <= pivot_about_contact;
                        // Ground contact can settle a quiet body; otherwise integrate
                        // signed fractional angle symmetrically in both directions.
                        if (bare_pig_only && was_grounded && step_vy >= 0) begin
                            angular_velocity_q8    <= 0;
                            moment_angle_remainder <= 0;
                            spin                   <= 0;
                            spin_frac              <= 0;
                            if (step_result_vx > 16'sd8) begin
                                proposed_tilt <= vehicle_tilt + 1'b1;
                            end else if (step_result_vx < -16'sd8) begin
                                proposed_tilt <= vehicle_tilt - 1'b1;
                            end else begin
                                proposed_tilt <= vehicle_tilt;
                            end
                        end else if (was_grounded && step_vy >= 0 && !step_support_unstable &&
                                     active_tip == 0 && supported_moment_accel == 0 &&
                                     (last_support_span_valid ||
                                      (clamped_angular_velocity < 14'sd256 && clamped_angular_velocity > -14'sd256))) begin
                            angular_velocity_q8    <= 0;
                            moment_angle_remainder <= 0;
                            spin                   <= 0;
                            spin_frac              <= 0;
                            if (!single_wheel_scraping && slope_target_ready && settle_error > 0 && !block_stationary_plus) begin
                                proposed_tilt <= tilt_plus_1;
                            end else if (!single_wheel_scraping && slope_target_ready && settle_error < 0 && !block_stationary_minus) begin
                                proposed_tilt <= tilt_minus_1;
                            end else begin
                                proposed_tilt <= vehicle_tilt;
                            end
                        end else if (air_leveling_snap) begin
                            // Once the descending cart is within one display angle of
                            // level and has little residual spin, settle it flat so a
                            // landing cannot visibly oscillate between +/- one step.
                            angular_velocity_q8    <= 0;
                            moment_angle_remainder <= 0;
                            spin                   <= 0;
                            spin_frac              <= 0;
                            proposed_tilt          <= 0;
                        end else if (!was_grounded && clamped_angular_velocity == 0) begin
                            angular_velocity_q8    <= 0;
                            moment_angle_remainder <= 0;
                            spin                   <= 0;
                            spin_frac              <= 0;
                            proposed_tilt          <= vehicle_tilt;
                        end else if ((clamped_angular_velocity > 0 && block_stationary_plus) ||
                                     (clamped_angular_velocity < 0 && block_stationary_minus)) begin
                            angular_velocity_q8    <= 0;
                            moment_angle_remainder <= 0;
                            spin                   <= 0;
                            spin_frac              <= 0;
                            proposed_tilt          <= vehicle_tilt;
                        end else begin
                            angular_velocity_q8 <= clamped_angular_velocity;
                            spin                <= clamped_angular_velocity >>> 8;
                            spin_frac           <= 0;
                            if (force_angle_sum >= 16'sd4096 && !block_stationary_plus) begin
                                proposed_tilt          <= tilt_plus_1;
                                moment_angle_remainder <= force_angle_sum - 16'sd4096;
                            end else if (force_angle_sum <= -16'sd4096 && !block_stationary_minus) begin
                                proposed_tilt          <= tilt_minus_1;
                                moment_angle_remainder <= force_angle_sum + 16'sd4096;
                            end else begin
                                proposed_tilt          <= vehicle_tilt;
                                moment_angle_remainder <= force_angle_sum[12:0];
                            end
                        end
                        phase <= PIVOT_START;
                    end
                    PIVOT_START: begin
                        phase <= PIVOT_WAIT;
                    end
                    PIVOT_WAIT: begin
                        if (pivot_valid) begin
                            step_pivot_x <= pivot_dx;
                            step_pivot_y <= pivot_dy;
                            phase        <= POSITION;
                        end
                    end
                    POSITION: begin
                        step_x_sum <= $signed({step_x[`LP_COORD_BITS-1], step_x}) +
                                      $signed({{(`LP_COORD_BITS-15){step_result_vx[15]}}, step_result_vx});
                        step_y_sum <= $signed({step_y[`LP_COORD_BITS-1], step_y}) +
                                      $signed({{(`LP_COORD_BITS-15){step_vy[15]}}, step_vy});
                        phase      <= step_moments_enabled ? APPLY_PIVOT : MAKE_REQUEST;
                    end
                    APPLY_PIVOT: begin
                        step_x_sum <= step_x_sum + $signed(step_pivot_x);
                        step_y_sum <= step_y_sum + $signed(step_pivot_y);
                        phase      <= MAKE_REQUEST;
                    end
                    MAKE_REQUEST: begin
                        // Saturate only at the numeric limits. World bounds are checked
                        // after committing movement, using the selected level size.
                        if (step_x_sum > POSITION_MAX) begin
                            proposed_x          <= POSITION_MAX[`LP_COORD_BITS-1:0];
                            pending_remainder_x <= 0;
                        end else if (step_x_sum < POSITION_MIN) begin
                            proposed_x          <= POSITION_MIN[`LP_COORD_BITS-1:0];
                            pending_remainder_x <= 0;
                        end else begin
                            proposed_x <= step_x_sum[`LP_COORD_BITS-1:0];
                        end
                        if (step_y_sum > POSITION_MAX) begin
                            proposed_y <= POSITION_MAX[`LP_COORD_BITS-1:0];
                        end else if (step_y_sum < POSITION_MIN) begin
                            proposed_y <= POSITION_MIN[`LP_COORD_BITS-1:0];
                        end else begin
                            proposed_y <= step_y_sum[`LP_COORD_BITS-1:0];
                        end
                        proposed_vx <= step_result_vx;
                        proposed_vy <= step_vy;
                        phase       <= SEND;
                    end
                    SEND: begin
                        if (move_ready) begin
                            phase <= WAIT_RESPONSE;
                        end
                    end
                    WAIT_RESPONSE: begin
                        if (response_valid) begin
                            vehicle_x <= corrected_x;
                            vehicle_y <= corrected_y;
                            // An error of more than 12 pixels (teleport, retry or a large
                            // collision correction) is not smoothed. A corrected x
                            // also snaps immediately when a wall changes the accepted
                            // contact position; otherwise the display pose would drag
                            // through the wall for several frames.
                            if (display_x_error > 22'sd3072 || display_x_error < -22'sd3072 ||
                                corrected_x != proposed_x) begin
                                display_x  <= corrected_x;
                                display_vx <= 0;
                            end else begin
                                // Correct thirty-one thirty-seconds of the remaining
                                // horizontal error. This leaves only a small
                                // sub-pixel interpolation step while keeping the
                                // rendered wheels aligned with the accepted terrain
                                // sample. Large corrections still take the snap path
                                // above, so retry and wall contacts cannot drag.
                                display_x  <= display_x_guess + (display_x_error >>> 1) +
                                              (display_x_error >>> 2) + (display_x_error >>> 3) +
                                              (display_x_error >>> 4) + (display_x_error >>> 5);
                                display_vx <= 0;
                            end
                            // Collision has already found the exact supported pose.
                            // Smooth 1-2px terrain stair-steps while rolling on a slope,
                            // and add a 0.5px wheel suspension compression on landing.
                            if (grounded) begin
                                if (wheel_landing_bounce) begin
                                    display_y  <= corrected_y + 20'sd128;
                                    display_vy <= 0;
                                end else if (grounded_stair_step) begin
                                    display_y  <= $signed(display_y) + (grounded_y_error >>> 1) +
                                                  (grounded_y_error >>> 2);
                                    display_vy <= corrected_vy;
                                end else begin
                                    display_y  <= corrected_y;
                                    display_vy <= corrected_vy;
                                end
                            end else if (display_error > 22'sd3072 || display_error < -22'sd3072) begin
                                display_y  <= corrected_y;
                                display_vy <= 0;
                            end else begin
                                display_y  <= display_guess + (display_error >>> 1);
                                display_vy <= display_vy + (display_error >>> 3);
                            end
                            vehicle_tilt <= sanitize_tilt(corrected_tilt);
                            if (!grounded || (corrected_vy < -16'sd16) || (corrected_vy > 16'sd64) ||
                                moved_from_anchor || (supported_moment_accel != 16'sd0)) begin
                                last_turn_valid        <= 1'b0;
                                equilibrium_count      <= 2'd0;
                                unstable_settled_dir   <= 2'sd0;
                                stationary_anchor_x_px <= $signed(corrected_x[19:8]);
                            end else if (sanitize_tilt(corrected_tilt) != sanitize_tilt(previous_tilt)) begin
                                last_turn_valid        <= 1'b1;
                                equilibrium_count      <= 2'd0;
                                last_turn_from_tilt    <= sanitize_tilt(previous_tilt);
                                stationary_anchor_x_px <= $signed(corrected_x[19:8]);
                                if (step_support_unstable || (active_tip != 2'sd0)) begin
                                    unstable_settled_dir <= (sanitize_tilt(corrected_tilt - previous_tilt) > 0) ? 2'sd1 : -2'sd1;
                                end
                            end else if (response_at_equilibrium) begin
                                if (equilibrium_count == 2'd3) begin
                                    last_turn_valid <= 1'b0;
                                end else begin
                                    equilibrium_count <= equilibrium_count + 1'b1;
                                end
                            end else begin
                                equilibrium_count <= 2'd0;
                            end
                            last_tip                      <= grounded ? tip_dir : 2'sd0;
                            last_support_unstable         <= grounded && support_unstable;
                            last_support_span_valid       <= grounded && support_span_valid;
                            last_support_wheel_count      <= support_wheel_count;
                            last_support_left_q2          <= support_left_q2;
                            last_support_right_q2         <= support_right_q2;
                            last_support_y_q2             <= support_y_q2;
                            last_support_endpoint_y_valid <= grounded && support_endpoint_y_valid;
                            last_support_left_y_q2        <= support_left_y_q2;
                            last_support_right_y_q2       <= support_right_y_q2;
                            last_ground_slope_valid       <= grounded && ground_slope_valid &&
                                                             ground_slope >= -8'sd16 && ground_slope <= 8'sd16;
                            // A wall or roof that blocks an airborne turn stops the spin.
                            if ((step_moments_enabled || !grounded) && corrected_tilt != proposed_tilt) begin
                                spin                   <= 0;
                                spin_frac              <= 0;
                                angular_velocity_q8    <= 0;
                                moment_angle_remainder <= 0;
                            end
                            velocity_x   <= corrected_vx;
                            velocity_y   <= corrected_vy;
                            was_grounded <= grounded;
                            if (grounded && ground_slope_valid && ground_slope >= -8'sd16 && ground_slope <= 8'sd16) begin
                                last_ground_slope <= ground_slope;
                            end else begin
                                last_ground_slope <= 0;
                            end
                            if (!grounded || !unpowered_run) begin
                                bowl_osc_count     <= 0;
                                prev_nonzero_slope <= 0;
                            end else if (ground_slope_valid && ground_slope >= -8'sd16 && ground_slope <= 8'sd16 && ground_slope != 0) begin
                                if ((prev_nonzero_slope > 0 && ground_slope < 0) || (prev_nonzero_slope < 0 && ground_slope > 0)) begin
                                    if (bowl_osc_count != 2'd3) begin
                                        bowl_osc_count <= bowl_osc_count + 1'b1;
                                    end
                                end
                                prev_nonzero_slope <= ground_slope;
                            end
                            // A wall/contact correction must discard pre-contact carry.
                            if (corrected_vx == proposed_vx && corrected_x == proposed_x) begin
                                remainder_x <= pending_remainder_x;
                            end else begin
                                remainder_x <= 0;
                            end
                            if (corrected_vy == proposed_vy && corrected_y == proposed_y) begin
                                remainder_y <= pending_remainder_y;
                            end else begin
                                remainder_y <= 0;
                            end
                            remainder_mass     <= step_mass;
                            movement_committed <= 1;
                            phase              <= WAIT_WORLD;
                        end
                    end
                    WAIT_WORLD: begin
                        if (update_release) begin
                            phase <= IDLE;
                        end
                    end
                    default: begin
                        phase <= IDLE;
                    end
                endcase
            end
        end
    end
endmodule

